import React, { useState } from 'react'
import {
  FileText, Download, Eye, Plus, BarChart2,
  AlertCircle, Brain, Wrench, ArrowRightLeft, CheckCircle
} from 'lucide-react'
import { useDemo } from '../context/DemoContext'
import { mockReports } from '../data/mockReports'
import { Card, CardHeader, CardTitle, CardContent } from '../components/ui/Card'
import { Button } from '../components/ui/Button'
import { Badge } from '../components/ui/Badge'
import { Modal } from '../components/ui/Modal'
import { useToast } from '../components/ui/Toast'
import { formatDateTime } from '../utils/format'
import type { Report } from '../types'

const TYPE_ICONS: Record<string, React.ComponentType<{ className?: string }>> = {
  performance: BarChart2,
  incident:    AlertCircle,
  diagnosis:   Brain,
  recovery:    Wrench,
  comparison:  ArrowRightLeft,
}

const TYPE_COLORS: Record<string, string> = {
  performance: 'text-blue-700 bg-blue-50 border-blue-200',
  incident:    'text-red-700 bg-red-50 border-red-200',
  diagnosis:   'text-purple-700 bg-purple-50 border-purple-200',
  recovery:    'text-teal-700 bg-teal-50 border-teal-200',
  comparison:  'text-orange-700 bg-orange-50 border-orange-200',
}

export function Reports() {
  const { demoState, demoReport, generateReport } = useDemo()
  const { toast } = useToast()
  const [viewReport, setViewReport] = useState<Report | null>(null)

  const allReports = [
    ...(demoReport ? [demoReport] : []),
    ...mockReports,
  ]

  const handleGenerate = () => {
    if (!demoState.recoveryAction || demoState.recoveryAction.status !== 'completed') {
      toast('Complete the demo recovery workflow first.', 'warning')
      return
    }
    generateReport()
    toast('Recovery report generated successfully!', 'success')
  }

  const handleDownloadPDF = (report: Report) => {
    // Simulate PDF download
    const content = [
      `NETMEDIC REPORT`,
      `===============`,
      `Title: ${report.title}`,
      `ID: ${report.id}`,
      `Date: ${formatDateTime(report.createdAt)}`,
      `Status: ${report.status.toUpperCase()}`,
      report.relatedIncident ? `Related Incident: ${report.relatedIncident}` : '',
      ``,
      `SUMMARY`,
      `-------`,
      report.summary,
      ``,
      ...report.sections.flatMap(s => [
        `${s.title.toUpperCase()}`,
        `-`.repeat(s.title.length),
        s.content,
        ``,
      ]),
      ``,
      `Generated by NetMedic Demo — This is a simulated report.`,
    ].join('\n')

    const blob = new Blob([content], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${report.id}.txt`
    a.click()
    URL.revokeObjectURL(url)
    toast('Report downloaded.', 'success')
  }

  const handleExportCSV = (report: Report) => {
    const rows = [
      ['Field', 'Value'],
      ['Report ID', report.id],
      ['Title', report.title],
      ['Type', report.type],
      ['Created', formatDateTime(report.createdAt)],
      ['Status', report.status],
      ['Related Incident', report.relatedIncident ?? '—'],
      ['Summary', report.summary],
      ...report.sections.map(s => [s.title, s.content]),
    ]
    const csv = rows.map(r => r.map(c => `"${c.replace(/"/g, '""')}"`).join(',')).join('\n')
    const blob = new Blob([csv], { type: 'text/csv' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${report.id}.csv`
    a.click()
    URL.revokeObjectURL(url)
    toast('CSV exported.', 'success')
  }

  return (
    <div className="space-y-5">
      {/* Generate report */}
      <Card className="gradient-brand-soft border-brand-teal/20">
        <div className="flex items-center justify-between flex-wrap gap-3">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 bg-brand-blue rounded-xl flex items-center justify-center">
              <FileText className="w-5 h-5 text-white" />
            </div>
            <div>
              <h2 className="font-semibold text-brand-dark">Network Reports</h2>
              <p className="text-xs text-gray-500">Generate and download incident, performance, and recovery reports</p>
            </div>
          </div>
          <Button
            variant="primary"
            size="md"
            icon={<Plus className="w-4 h-4" />}
            onClick={handleGenerate}
            disabled={!!demoReport}
          >
            {demoReport ? 'Demo Report Generated' : 'Generate Recovery Report'}
          </Button>
        </div>
      </Card>

      {/* Stats row */}
      <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
        {[
          { type: 'performance', label: 'Performance' },
          { type: 'incident',    label: 'Incident' },
          { type: 'diagnosis',   label: 'Diagnosis' },
          { type: 'recovery',    label: 'Recovery' },
          { type: 'comparison',  label: 'Comparison' },
        ].map(({ type, label }) => {
          const Icon = TYPE_ICONS[type]
          const count = allReports.filter(r => r.type === type).length
          return (
            <div key={type} className={`flex items-center gap-2 p-3 rounded-xl border text-xs font-medium ${TYPE_COLORS[type]}`}>
              <Icon className="w-4 h-4" />
              <span>{label}</span>
              <span className="ml-auto font-bold">{count}</span>
            </div>
          )
        })}
      </div>

      {/* Reports table */}
      <Card>
        <CardHeader>
          <CardTitle>All Reports ({allReports.length})</CardTitle>
        </CardHeader>
        <CardContent>
          <div className="space-y-3">
            {allReports.map(report => {
              const Icon = TYPE_ICONS[report.type] ?? FileText
              return (
                <div key={report.id} className="flex items-start justify-between p-4 rounded-xl border border-gray-100 bg-gray-50/50 hover:border-gray-200 hover:bg-gray-50 transition-all">
                  <div className="flex items-start gap-3 min-w-0">
                    <div className={`p-2 rounded-lg flex-shrink-0 ${TYPE_COLORS[report.type]}`}>
                      <Icon className="w-4 h-4" />
                    </div>
                    <div className="min-w-0">
                      <div className="flex items-center gap-2 flex-wrap">
                        <p className="text-sm font-semibold text-brand-dark">{report.title}</p>
                        {report.id === demoReport?.id && (
                          <Badge className="text-brand-teal bg-teal-50 border-teal-200">New</Badge>
                        )}
                      </div>
                      <p className="text-xs text-gray-500 mt-0.5">
                        {report.id} · {formatDateTime(report.createdAt)}
                        {report.relatedIncident && ` · ${report.relatedIncident}`}
                      </p>
                      <p className="text-xs text-gray-600 mt-1 line-clamp-2">{report.summary}</p>
                    </div>
                  </div>
                  <div className="flex items-center gap-1.5 flex-shrink-0 ml-4">
                    <Badge className={report.status === 'final' ? 'text-teal-700 bg-teal-50 border-teal-200' : 'text-gray-600 bg-gray-50 border-gray-200'}>
                      {report.status === 'final' ? <CheckCircle className="w-2.5 h-2.5 mr-1" /> : null}
                      {report.status.charAt(0).toUpperCase() + report.status.slice(1)}
                    </Badge>
                    <Button variant="ghost" size="sm" icon={<Eye className="w-3.5 h-3.5" />}
                      onClick={() => setViewReport(report)}>
                      Preview
                    </Button>
                    <Button variant="ghost" size="sm" icon={<Download className="w-3.5 h-3.5" />}
                      onClick={() => handleDownloadPDF(report)}>
                      PDF
                    </Button>
                    <Button variant="ghost" size="sm"
                      onClick={() => handleExportCSV(report)}>
                      CSV
                    </Button>
                  </div>
                </div>
              )
            })}
          </div>
        </CardContent>
      </Card>

      {/* Report preview modal */}
      <Modal open={!!viewReport} onClose={() => setViewReport(null)} title={viewReport?.title ?? ''} size="lg">
        {viewReport && (
          <div className="space-y-4 max-h-[70vh] overflow-y-auto scrollbar-thin pr-1">
            <div className="flex items-center gap-2 flex-wrap">
              <Badge className={TYPE_COLORS[viewReport.type]}>
                {viewReport.type.charAt(0).toUpperCase() + viewReport.type.slice(1)}
              </Badge>
              <span className="text-xs text-gray-500 font-mono">{viewReport.id}</span>
              <span className="text-xs text-gray-400">{formatDateTime(viewReport.createdAt)}</span>
              {viewReport.relatedIncident && (
                <span className="text-xs text-brand-blue">{viewReport.relatedIncident}</span>
              )}
            </div>

            <div className="bg-gray-50 rounded-xl p-4">
              <p className="text-xs font-semibold text-gray-600 mb-2 uppercase tracking-wide">Executive Summary</p>
              <p className="text-sm text-gray-700 leading-relaxed">{viewReport.summary}</p>
            </div>

            {viewReport.sections.map((section, i) => (
              <div key={i} className="border-t border-gray-100 pt-4">
                <h3 className="text-sm font-semibold text-brand-dark mb-2">{section.title}</h3>
                <p className="text-sm text-gray-700 leading-relaxed">{section.content}</p>
              </div>
            ))}

            <div className="border-t border-gray-100 pt-4 flex gap-2 justify-end">
              <Button variant="outline" size="sm" icon={<Download className="w-3.5 h-3.5" />}
                onClick={() => handleDownloadPDF(viewReport)}>Download PDF</Button>
              <Button variant="outline" size="sm"
                onClick={() => handleExportCSV(viewReport)}>Export CSV</Button>
            </div>
          </div>
        )}
      </Modal>
    </div>
  )
}
